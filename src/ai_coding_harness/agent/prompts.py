def _read_output_style(settings: Settings) -> str:
    """读主智能体回给用户的「输出形态」规则（仓库根相对路径，见 ``Settings``）。

    缺失**当场抛错**（与 ``sandbox/provider._read_asset`` 同一态度）：规则没生效却静默
    继续，等于线上跑着一份没人知道的提示词 —— 那比启动失败更难发现。
    """
    path = _REPO_ROOT / settings.agent_output_style_file
    if not path.is_file():
        raise RuntimeError(f"输出形态规则文件缺失：{path}")
    return path.read_text(encoding="utf-8").strip()


def build_main_prompt(
        repo_url: str,
        *,
        form: str = ORCHESTRATE_FORM,
        settings: Settings | None = None,
) -> str:
    """主智能体提示词，附加本次会话的目标仓库与输出形态规则。

    ``form`` 选装配形态（见 ``agent/profiles.py``）：``qa`` / ``plan`` 各自单智能体，
    ``orchestrate`` 挂三个子智能体。

    输出形态规则只在这里拼 —— 三个形态的主智能体都经过本函数，而三种子智能体的提示词
    各是独立常量（``PLANNER_PROMPT`` / ``CODER_PROMPT`` / ``REVIEWER_PROMPT``），不经过，
    所以「只约束主智能体」是结构保证的，不靠在别处记得别加。
    """
    prompt = _MAIN_PROMPTS[form]
    style = _read_output_style(settings or get_settings())
    return (
            prompt
            + f"\n\n## 目标仓库\n- 仓库地址：{repo_url}\n"
            + "- 操作在 `/ai_coding/project/` 下进行。"
            + "\n\n" + style
    )


